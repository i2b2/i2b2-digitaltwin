-- Aggregate Oracle extract for loyalty-burden-atlas.html.
-- Save the result grid as loyalty_landscape.csv with column headers.
-- No patient identifiers are returned. Cells smaller than MIN_CELL_SIZE
-- are omitted; use the disclosure threshold required by your institution.
--
-- Edit the constants in PARAMS. A typed NULL includes every value.

WITH PARAMS AS (
    SELECT
        CAST(NULL AS VARCHAR2(100)) AS SITE_FILTER,
        CAST(NULL AS VARCHAR2(100)) AS COHORT_FILTER,
        CAST(NULL AS NUMBER) AS LOOKBACK_FILTER,
        CAST(NULL AS CHAR(1)) AS GENDERED_FILTER,
        10 AS MIN_CELL_SIZE
    FROM DUAL
), MATCHED AS (
    SELECT
        R.SITE,
        R.COHORT_NAME,
        R.LOOKBACK_YEARS,
        R.GENDER_DENOMINATORS_YN,
        R.PATIENT_NUM,
        NVL(TRIM(R.AGE_GRP), 'Unknown') AS AGE_GRP,
        NVL(TRIM(R.SEX), 'Unknown') AS SEX,
        R.PREDICTED_SCORE,
        NVL(C.CHARLSON_INDEX, 0) AS CHARLSON_INDEX,
        C.CHARLSON_10YR_PROB,
        R.NUM_DX1, R.NUM_DX2, R.MED_USE1, R.MED_USE2,
        R.MAMMOGRAPHY, R.PAP_TEST, R.PSA_TEST, R.COLONOSCOPY,
        R.FECAL_OCCULT_TEST, R.FLU_SHOT, R.PNEUMOCOCCAL_VACCINE,
        R.BMI, R.A1C, R.MEDICAL_EXAM,
        R.INP1_OPT1_VISIT, R.OPT2_VISIT, R.ED_VISIT,
        R.MDVISIT_PNAME2, R.MDVISIT_PNAME3, R.ROUTINE_CARE_2
    FROM DT_LOYALTY_RESULT R
    JOIN DT_LOYALTY_RESULT_CHARLSON C
      ON C.SITE = R.SITE
     AND C.COHORT_NAME = R.COHORT_NAME
     AND C.PATIENT_NUM = R.PATIENT_NUM
     AND C.LOOKBACK_YEARS = R.LOOKBACK_YEARS
     AND C.GENDER_DENOMINATORS_YN = R.GENDER_DENOMINATORS_YN
    CROSS JOIN PARAMS P
    WHERE (P.SITE_FILTER IS NULL OR R.SITE = P.SITE_FILTER)
      AND (P.COHORT_FILTER IS NULL OR R.COHORT_NAME = P.COHORT_FILTER)
      AND (P.LOOKBACK_FILTER IS NULL OR R.LOOKBACK_YEARS = P.LOOKBACK_FILTER)
      AND (P.GENDERED_FILTER IS NULL OR R.GENDER_DENOMINATORS_YN = P.GENDERED_FILTER)
), SCORED AS (
    SELECT M.*,
        NTILE(10) OVER (
            PARTITION BY SITE, COHORT_NAME, LOOKBACK_YEARS, GENDER_DENOMINATORS_YN
            ORDER BY PREDICTED_SCORE, PATIENT_NUM
        ) AS LOYALTY_DECILE,
        CASE
            WHEN CHARLSON_INDEX = 0 THEN '0'
            WHEN CHARLSON_INDEX = 1 THEN '1'
            WHEN CHARLSON_INDEX = 2 THEN '2'
            WHEN CHARLSON_INDEX BETWEEN 3 AND 4 THEN '3-4'
            ELSE '5+'
        END AS CHARLSON_BAND
    FROM MATCHED M
), AGGREGATED AS (
    SELECT
        SITE, COHORT_NAME, LOOKBACK_YEARS, GENDER_DENOMINATORS_YN,
        AGE_GRP, SEX, LOYALTY_DECILE, CHARLSON_BAND,
        COUNT(*) AS PATIENT_COUNT,
        AVG(CAST(PREDICTED_SCORE AS NUMBER)) AS MEAN_LOYALTY_SCORE,
        AVG(CAST(CHARLSON_INDEX AS NUMBER)) AS MEAN_CHARLSON_INDEX,
        AVG(CAST(CHARLSON_10YR_PROB AS NUMBER)) AS MEAN_CHARLSON_10YR_PROB,
        SUM(CAST(NUM_DX1 AS NUMBER)) AS NUM_DX1_COUNT,
        SUM(CAST(NUM_DX2 AS NUMBER)) AS NUM_DX2_COUNT,
        SUM(CAST(MED_USE1 AS NUMBER)) AS MED_USE1_COUNT,
        SUM(CAST(MED_USE2 AS NUMBER)) AS MED_USE2_COUNT,
        SUM(CAST(MAMMOGRAPHY AS NUMBER)) AS MAMMOGRAPHY_COUNT,
        SUM(CAST(PAP_TEST AS NUMBER)) AS PAP_TEST_COUNT,
        SUM(CAST(PSA_TEST AS NUMBER)) AS PSA_TEST_COUNT,
        SUM(CAST(COLONOSCOPY AS NUMBER)) AS COLONOSCOPY_COUNT,
        SUM(CAST(FECAL_OCCULT_TEST AS NUMBER)) AS FECAL_OCCULT_TEST_COUNT,
        SUM(CAST(FLU_SHOT AS NUMBER)) AS FLU_SHOT_COUNT,
        SUM(CAST(PNEUMOCOCCAL_VACCINE AS NUMBER)) AS PNEUMOCOCCAL_VACCINE_COUNT,
        SUM(CAST(BMI AS NUMBER)) AS BMI_COUNT,
        SUM(CAST(A1C AS NUMBER)) AS A1C_COUNT,
        SUM(CAST(MEDICAL_EXAM AS NUMBER)) AS MEDICAL_EXAM_COUNT,
        SUM(CAST(INP1_OPT1_VISIT AS NUMBER)) AS INP1_OPT1_VISIT_COUNT,
        SUM(CAST(OPT2_VISIT AS NUMBER)) AS OPT2_VISIT_COUNT,
        SUM(CAST(ED_VISIT AS NUMBER)) AS ED_VISIT_COUNT,
        SUM(CAST(MDVISIT_PNAME2 AS NUMBER)) AS MDVISIT_PNAME2_COUNT,
        SUM(CAST(MDVISIT_PNAME3 AS NUMBER)) AS MDVISIT_PNAME3_COUNT,
        SUM(CAST(ROUTINE_CARE_2 AS NUMBER)) AS ROUTINE_CARE_2_COUNT
    FROM SCORED
    GROUP BY SITE, COHORT_NAME, LOOKBACK_YEARS, GENDER_DENOMINATORS_YN,
        AGE_GRP, SEX, LOYALTY_DECILE, CHARLSON_BAND
)
SELECT A.*
FROM AGGREGATED A
CROSS JOIN PARAMS P
WHERE A.PATIENT_COUNT >= P.MIN_CELL_SIZE
ORDER BY A.SITE, A.COHORT_NAME, A.LOOKBACK_YEARS,
    A.GENDER_DENOMINATORS_YN, A.AGE_GRP, A.SEX, A.LOYALTY_DECILE,
    CASE A.CHARLSON_BAND
        WHEN '0' THEN 0
        WHEN '1' THEN 1
        WHEN '2' THEN 2
        WHEN '3-4' THEN 3
        ELSE 4
    END;
